#!/usr/bin/env bash
# Прожарка постановки «ленивым сеньором»: что здесь лишнее и что выкинуть.
#
#   bash scripts/grill-spec.sh docs/tasks/184/spec.md
#   cat spec.md | bash scripts/grill-spec.sh
#
# Запускается РУКАМИ, в пайплайн не встроен и ничего не решает сам — вето у человека.
# Вызов одноразовый, без тулов и без MCP, из пустого каталога: ревьюер не должен получить
# наши же правила из CLAUDE.md, иначе он перестанет быть внешним взглядом.
# Замер #184: медиана $0.06 за вызов, ~30 с. Полная форма вызова (с тулами и MCP) стоит
# в 4.6 раза дороже при том же ответе.
set -euo pipefail

MODEL=${GRILL_MODEL:-'claude-opus-5[1m]'}

SRC=${1:--}
if [ "$SRC" != "-" ] && [ ! -r "$SRC" ]; then
    echo "grill-spec: файл не читается: $SRC" >&2
    exit 2
fi

# Каталог нужен пустым — как cwd для вызова, чтобы ревьюеру не подмешался CLAUDE.md репозитория.
WORK=$(mktemp -d)
trap 'rm -f -- "$WORK/spec"; rmdir "$WORK" 2>/dev/null || echo "grill-spec: $WORK непуст, оставлен" >&2' EXIT

# Вход всегда кладём в файл: и аргумент, и stdin проверяются одним и тем же способом.
# NUL ищет grep — паттерн обязан экранировать он, а не bash: в переменной bash NUL не хранит,
# и $'\x00' схлопнулся бы в пустую строку, которая матчит всё подряд.
cat -- "$SRC" > "$WORK/spec"
if LC_ALL=C grep -qaP '\x00' -- "$WORK/spec"; then
    echo "grill-spec: во входе есть NUL — это не текст постановки" >&2
    exit 2
fi
SPEC=$(cat -- "$WORK/spec")
if [ -z "${SPEC//[[:space:]]/}" ]; then
    echo "grill-spec: постановка пуста (аргумент — файл, либо подай текст на stdin)" >&2
    exit 2
fi

PERSONA='Ты — ленивый старший инженер. Твоя работа — не дать команде сделать лишнее.
Ты исходишь из того, что самый дорогой код — написанный. Ты спрашиваешь в таком порядке:
это вообще должно существовать? это уже есть готовое? это делает платформа или стандартная
библиотека? это можно в одну строку? Ты ненавидишь абстракции, введённые «на будущее»,
интерфейсы с одной реализацией, конфигурируемость, которую не просили, и обработку сценариев,
которые не наступят у этого предмета. Ты всегда соотносишь уровень строгости решения с ценой
ошибки у ЭТОГО предмета. Ты называешь, что конкретно выкинуть.

ФОРМАТ ОТВЕТА (обязателен). Максимум 5 находок, каждая — ОДНА строка вида:
BLOCKING | <утверждение>
SUGGESTION | <утверждение>
NIT | <утверждение>
BLOCKING = сломается, потеряются данные, вывод неверен, работа будет выброшена.
SUGGESTION = реальное улучшение. NIT = мелочь.
Если блокирующих проблем нет — так и напиши строкой `OK | блокирующих проблем не вижу`.
Никакой преамбулы, никакого резюме, никаких пояснений вне строк находок.'

# Убираем за собой `rmdir`, а не `rm -rf`: он физически не может снести ничего, кроме пустого
# каталога, поэтому чужие данные не пострадают даже при пустом `$WORK`. `rm -rf` в проекте запрещён.

RAW=$(cd "$WORK" && claude -p --model "$MODEL" --output-format json \
    --strict-mcp-config --mcp-config '{"mcpServers":{}}' --tools "" \
    --system-prompt "$PERSONA" "$SPEC")

RAW="$RAW" python3 - <<'PY'
import json, os, sys

try:
    d = json.loads(os.environ["RAW"])
except json.JSONDecodeError as e:
    sys.exit(f"grill-spec: CLI вернул не JSON ({e})")
if d.get("is_error") or not d.get("result"):
    sys.exit(f"grill-spec: вызов не дал ответа: {str(d)[:300]}")
print(d["result"].strip())
u = d["usage"]
print(f"[${d['total_cost_usd']:.3f}  {d['duration_ms'] / 1000:.0f}s  "
      f"out={u['output_tokens']} ток]", file=sys.stderr)
PY
